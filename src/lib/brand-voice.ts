// رسائل الخطأ الدافئة (بدل "فشل")
// ═══════════════════════════════════════════════════════════
type WarmErrorContext =
  | 'save'
  | 'load'
  | 'send'
  | 'payment'
  | 'network'
  | 'auth'
  | 'booking'
  | 'otp'
  | 'generic';

export function warmError(ctx: WarmErrorContext | string, detail?: string): string {
  const base: Record<WarmErrorContext, string> = {
    save: 'لم يكتمل الحفظ · حاولي خلال لحظات 🤍',
    load: 'لم نتمكّن من التحميل الآن · حاولي مجدّداً',
    send: 'لم نرسل الرسالة بعد · حاولي خلال دقيقة',
    payment: 'لم تكتمل عمليّة الدفع · حجزكِ ما زال محفوظاً لكِ 💛',
    network: 'تعثّر الاتصال · تحقّقي من الشبكة ثمّ حاولي 🤍',
    auth: 'لم نتمكّن من تسجيل دخولكِ الآن · تحقّقي من بياناتكِ',
    booking: 'لم نتمكّن من تأكيد الحجز · لا تقلقي، لم يُخصم أي مبلغ',
    otp: 'لم يصل الرمز بعد · حاولي خلال دقيقة أو اطلبي رمزاً جديداً',
    generic: 'تعثّر شيء بسيط · حاولي مرّة ثانية 🤍',
  };
  const key = (ctx in base ? ctx : 'generic') as WarmErrorContext;
  return detail ? `${base[key]} · ${detail}` : base[key];
}

